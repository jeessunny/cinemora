export const getNewReleases = () =>
  [...mockMovies].filter(m => m.year === 2024).sort(() => 0.5 - Math.random()).slice(0, 10);

export const getRecommended = (selectedGenres) => {
  let list = [];
  if (!selectedGenres || selectedGenres.length === 0) {
    list = [...mockMovies];
  } else {
    list = mockMovies.filter(m => m.genres.some(g => selectedGenres.includes(g)));
  }
  return list.sort(() => 0.5 - Math.random()).slice(0, 10);
};

export const searchMovies = (query) => {
  if (!query) return [];
  const q = query.toLowerCase();
  return mockMovies.filter(m =>
    m.title.toLowerCase().includes(q) ||
    m.genres.some(g => g.toLowerCase().includes(q)) ||
    m.cast.some(c => c.name.toLowerCase().includes(q))
  );
};
